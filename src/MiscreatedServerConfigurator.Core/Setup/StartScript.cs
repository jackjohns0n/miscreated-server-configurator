using System.Globalization;
using System.Text.RegularExpressions;

namespace MiscreatedServerConfigurator.Core.Setup;

/// <summary>A start script read back from disk.</summary>
/// <param name="IsOurs">True when the file carries the <c>MSC-START 1</c> marker.</param>
/// <param name="ServerDirectory">The <c>SERVER</c> variable, when ours set it.</param>
/// <param name="SteamCmdPath">The <c>STEAMCMD</c> variable, when ours set it.</param>
/// <param name="Settings">Launch settings filled from the file. Missing fields keep the editor defaults.</param>
/// <param name="Skipped">Lines from a foreign script that were not recognized. Empty for a script this app wrote.</param>
public readonly record struct ParsedStartScript(
    bool IsOurs,
    string? ServerDirectory,
    string? SteamCmdPath,
    LaunchSettings Settings,
    IReadOnlyList<string> Skipped);

/// <summary>
/// Writes and reads <c>StartServer.bat</c>. The script updates the dedicated server, clears the Mods folder, and starts the executable.
/// Workshop downloads stay in the app, where a failed anonymous download can be shown. The app never starts this script.
/// </summary>
public static partial class StartScript
{
    /// <summary>Marker on the second comment line of a script this app wrote.</summary>
    public const string Marker = "rem MSC-START 1";

    private static readonly string[] StructuralSetNames = { "BETA_ARGS", "EXTRA" };

    private static readonly Regex SetPattern = SetRegex();
    private static readonly Regex BindPattern = new(@"-sv_bind\s+(\S+)", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
    private static readonly Regex PortPattern = new(@"-sv_port\s+(\d+)", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
    private static readonly Regex IdPattern = new(@"-mis_gameserverid\s+(\d+)", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
    private static readonly Regex PlayersPattern = new(@"\+sv_maxplayers\s+(\d+)", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
    private static readonly Regex MapPattern = new(@"\+map\s+(\S+)", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
    private static readonly Regex BetaPattern = new(@"-beta\s+(\S+)", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
    private static readonly Regex BetaPasswordPattern = new(@"-betapassword\s+(\S+)", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);

    /// <summary>Builds the batch file for one server.</summary>
    /// <param name="serverDirectory">The server folder.</param>
    /// <param name="steamCmdExecutable">The shared <c>steamcmd.exe</c>.</param>
    /// <param name="settings">Launch settings. They must already be valid.</param>
    /// <returns>The batch file, with CRLF line endings.</returns>
    public static string Generate(string serverDirectory, string steamCmdExecutable, LaunchSettings settings)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(serverDirectory);
        ArgumentException.ThrowIfNullOrWhiteSpace(steamCmdExecutable);
        ArgumentNullException.ThrowIfNull(settings);
        var whitelist = settings.Whitelisted ? "1" : "0";
        var lines = new[]
        {
            "@echo off",
            "setlocal EnableExtensions",
            Marker,
            "rem Generated by Miscreated Server Configurator. The app does not run the server.",
            "rem Workshop mods are downloaded by the app into steamapps\\workshop, not by this script.",
            "set \"SERVER=" + serverDirectory + "\"",
            "set \"STEAMCMD=" + steamCmdExecutable + "\"",
            "set \"MAP=" + settings.Map + "\"",
            "set \"GAME_PORT=" + settings.GamePort.ToString(CultureInfo.InvariantCulture) + "\"",
            "set \"MAX_PLAYERS=" + settings.MaxPlayers.ToString(CultureInfo.InvariantCulture) + "\"",
            "set \"WHITELISTED=" + whitelist + "\"",
            "set \"MIS_GAMESERVERID=" + settings.MisGameServerId.ToString(CultureInfo.InvariantCulture) + "\"",
            "set \"SV_BIND=" + settings.SvBind + "\"",
            "set \"BETA=" + settings.Beta + "\"",
            "set \"BETAPASSWORD=" + settings.BetaPassword + "\"",
            ":restart",
            "if exist \"%SERVER%\\stop.txt\" (",
            "  echo stop.txt is present. Remove it before starting.",
            "  exit /b 0",
            ")",
            "set \"BETA_ARGS=\"",
            "if not \"%BETA%\"==\"\" set \"BETA_ARGS=-beta %BETA% -betapassword %BETAPASSWORD%\"",
            "\"%STEAMCMD%\" +force_install_dir \"%SERVER%\" +login anonymous +app_update 302200 %BETA_ARGS% validate +quit",
            "if errorlevel 1 (",
            "  \"%STEAMCMD%\" +force_install_dir \"%SERVER%\" +login anonymous +app_update 302200 %BETA_ARGS% validate +quit",
            "  if errorlevel 1 exit /b 1",
            ")",
            "if exist \"%SERVER%\\Mods\" rmdir /s /q \"%SERVER%\\Mods\"",
            "mkdir \"%SERVER%\\Mods\"",
            "set \"EXTRA=\"",
            "if \"%WHITELISTED%\"==\"1\" set \"EXTRA=-mis_whitelist\"",
            "\"%SERVER%\\Bin64_dedicated\\MiscreatedServer.exe\" -sv_bind %SV_BIND% %EXTRA% -sv_port %GAME_PORT% -mis_gameserverid %MIS_GAMESERVERID% +sv_maxplayers %MAX_PLAYERS% +map %MAP% +http_startserver",
            "choice /c QC /n /t 10 /d C /m \"Q quit, C continue\"",
            "if errorlevel 2 goto restart",
            "exit /b 0",
        };
        return string.Join("\r\n", lines) + "\r\n";
    }

    /// <summary>
    /// Reads a script. Ours is read from its <c>set</c> lines. A foreign script contributes the flags it contains,
    /// and every other non-structural line is returned in <see cref="ParsedStartScript.Skipped"/>.
    /// </summary>
    /// <param name="text">The batch file text.</param>
    /// <returns>The parse result. Settings start from the editor defaults.</returns>
    public static ParsedStartScript Parse(string text)
    {
        ArgumentNullException.ThrowIfNull(text);
        var isOurs = text.Contains(Marker, StringComparison.Ordinal);
        var settings = LaunchSettings.CreateDefault();
        string? server = null;
        string? steamCmd = null;
        var skipped = new List<string>();
        foreach (var raw in text.Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n'))
        {
            var line = raw.Trim();
            if (line.Length == 0)
            {
                continue;
            }

            if (TryReadSet(line, out var key, out var value))
            {
                if (ApplySet(key, value, settings, ref server, ref steamCmd))
                {
                    continue;
                }

                if (!isOurs && Array.IndexOf(StructuralSetNames, key) < 0)
                {
                    skipped.Add(line);
                }

                continue;
            }

            if (ApplyFlags(line, settings) || IsStructural(line))
            {
                continue;
            }

            if (!isOurs)
            {
                skipped.Add(line);
            }
        }

        return new ParsedStartScript(isOurs, server, steamCmd, settings, skipped);
    }

    private static bool TryReadSet(string line, out string key, out string value)
    {
        var match = SetPattern.Match(line);
        if (!match.Success)
        {
            key = string.Empty;
            value = string.Empty;
            return false;
        }

        key = match.Groups[1].Value;
        value = match.Groups[2].Value;
        return true;
    }

    private static bool ApplySet(string key, string value, LaunchSettings settings, ref string? server, ref string? steamCmd)
    {
        switch (key)
        {
            case "SERVER":
                server = value;
                return true;
            case "STEAMCMD":
                steamCmd = value;
                return true;
            case "MAP":
                settings.Map = value;
                return true;
            case "GAME_PORT" when int.TryParse(value, NumberStyles.None, CultureInfo.InvariantCulture, out var port):
                settings.GamePort = port;
                return true;
            case "MAX_PLAYERS" when int.TryParse(value, NumberStyles.None, CultureInfo.InvariantCulture, out var players):
                settings.MaxPlayers = players;
                return true;
            case "WHITELISTED":
                settings.Whitelisted = value == "1";
                return true;
            case "MIS_GAMESERVERID" when int.TryParse(value, NumberStyles.None, CultureInfo.InvariantCulture, out var id):
                settings.MisGameServerId = id;
                return true;
            case "SV_BIND":
                settings.SvBind = value;
                return true;
            case "BETA":
                settings.Beta = value;
                return true;
            case "BETAPASSWORD":
                settings.BetaPassword = value;
                return true;
            default:
                return false;
        }
    }

    private static bool ApplyFlags(string line, LaunchSettings settings)
    {
        var recognized = false;
        var bind = BindPattern.Match(line);
        if (bind.Success && !bind.Groups[1].Value.StartsWith('%'))
        {
            settings.SvBind = bind.Groups[1].Value;
            recognized = true;
        }

        var port = PortPattern.Match(line);
        if (port.Success && int.TryParse(port.Groups[1].Value, NumberStyles.None, CultureInfo.InvariantCulture, out var portNumber))
        {
            settings.GamePort = portNumber;
            recognized = true;
        }

        var id = IdPattern.Match(line);
        if (id.Success && int.TryParse(id.Groups[1].Value, NumberStyles.None, CultureInfo.InvariantCulture, out var idNumber))
        {
            settings.MisGameServerId = idNumber;
            recognized = true;
        }

        if (line.Contains("-mis_whitelist", StringComparison.OrdinalIgnoreCase)
            && !line.Contains("%EXTRA%", StringComparison.OrdinalIgnoreCase))
        {
            settings.Whitelisted = true;
            recognized = true;
        }

        var players = PlayersPattern.Match(line);
        if (players.Success && int.TryParse(players.Groups[1].Value, NumberStyles.None, CultureInfo.InvariantCulture, out var playerCount))
        {
            settings.MaxPlayers = playerCount;
            recognized = true;
        }

        var map = MapPattern.Match(line);
        if (map.Success && !map.Groups[1].Value.StartsWith('%'))
        {
            settings.Map = map.Groups[1].Value;
            recognized = true;
        }

        var beta = BetaPattern.Match(line);
        if (beta.Success && !beta.Groups[1].Value.StartsWith('%'))
        {
            settings.Beta = beta.Groups[1].Value;
            recognized = true;
        }

        var password = BetaPasswordPattern.Match(line);
        if (password.Success && !password.Groups[1].Value.StartsWith('%'))
        {
            settings.BetaPassword = password.Groups[1].Value;
            recognized = true;
        }

        return recognized
            || line.Contains("steamcmd", StringComparison.OrdinalIgnoreCase)
            || line.Contains("MiscreatedServer.exe", StringComparison.OrdinalIgnoreCase);
    }

    private static bool IsStructural(string line)
    {
        if (line.StartsWith(':'))
        {
            return true;
        }

        var head = line.Split(' ', 2)[0].TrimStart('@');
        return head.Equals("echo", StringComparison.OrdinalIgnoreCase)
            || head.Equals("rem", StringComparison.OrdinalIgnoreCase)
            || line.StartsWith("::", StringComparison.Ordinal)
            || head.Equals("setlocal", StringComparison.OrdinalIgnoreCase)
            || head.Equals("endlocal", StringComparison.OrdinalIgnoreCase)
            || head.Equals("if", StringComparison.OrdinalIgnoreCase)
            || head.Equals("goto", StringComparison.OrdinalIgnoreCase)
            || head.Equals("choice", StringComparison.OrdinalIgnoreCase)
            || head.Equals("exit", StringComparison.OrdinalIgnoreCase)
            || head.Equals("mkdir", StringComparison.OrdinalIgnoreCase)
            || head.Equals("rmdir", StringComparison.OrdinalIgnoreCase)
            || head.Equals("pause", StringComparison.OrdinalIgnoreCase)
            || head.Equals("title", StringComparison.OrdinalIgnoreCase)
            || head.Equals("cd", StringComparison.OrdinalIgnoreCase)
            || head.Equals("pushd", StringComparison.OrdinalIgnoreCase)
            || head.Equals("popd", StringComparison.OrdinalIgnoreCase)
            || head.Equals("call", StringComparison.OrdinalIgnoreCase);
    }

    [GeneratedRegex("^set \"([A-Za-z0-9_]+)=(.*)\"$", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant)]
    private static partial Regex SetRegex();
}
